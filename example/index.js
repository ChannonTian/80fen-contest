'use strict';

module.exports = () => ({

  name: '改成你的名字',

  /* 发牌途中,每发到你手上一张牌就问你一次(一局 100 次)。
   * 发完之后还会绕圈再问,直到一整圈没人动作。
   * 返回 null = 这次不亮;返回 {suit, strength} = 现在就亮。
   *   strength: 1=一张级数牌  2=一对级数牌  3=小王对(反无主)  4=大王对(反无主)
   *   反无主时 suit 传 null。
   * 返回你手上根本没有的组合会被记违规(不罚分,当作没亮)。 */
  onDeal(view) {
    return null;
  },

  /* 定主之后,如果你手牌太差(分 ≤ 15 或主牌 ≤ 3 张),裁判会问你要不要掀桌重发。
   * 只有庄家的对方队会被问。返回 true 就重发。 */
  onRebel(view) {
    return false;
  },

  /* 你是庄家,手上 33 张(25 + 底牌 8),扣掉 8 张。
   * 必须**恰好 8 张、全在手上、无重复**,否则裁判替你扣并罚 40 分。 */
  discard(view) {
    return view.hand.slice(0, 8);
  },

  /* 轮到你领出。返回 Card[] 或 {cards: Card[]}。 */
  lead(view) {
    return [view.hand[0]];
  },

  /* 轮到你跟牌。plays 是本墩已经出的几手,plays[0] 是领出。
   * 跟牌规矩很啰嗦(张数、有则必跟、对子也得跟、拖拉机必须跟),
   * 全在 RULES.md §S3。跟错了裁判替你出,并按**替出的张数 × 5 分**罚。 */
  follow(view, plays) {
    return view.hand.slice(0, plays[0].cards.length);
  },

});
